#!/bin/sh
# Regenerates prometheusrule.yaml from the single source of truth, deployment/observability/prometheus/rules/
# apigw-alerts.yml (validated by promtool and ObservabilityIT). validate.sh fails if the two drift.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
src="$here/../../../observability/prometheus/rules/apigw-alerts.yml"
{
  echo "# GENERATED by generate-prometheusrule.sh from deployment/observability/prometheus/rules/apigw-alerts.yml."
  echo "apiVersion: monitoring.coreos.com/v1"
  echo "kind: PrometheusRule"
  echo "metadata:"
  echo "  name: apigw"
  echo "spec:"
  grep -v '^#' "$src" | sed 's/^/  /'
} > "$here/prometheusrule.yaml"
